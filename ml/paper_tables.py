"""Generate the LaTeX localization table directly from recorded experiments."""

import json
from pathlib import Path


def percentage(value):
    return "n/a" if value is None else f"{value * 100:.1f}"


def row(label, report):
    precision = report["bootstrap_95"]["precision_iou25"]
    bounds = "--".join(map(percentage, precision)) if precision else "n/a"
    return (
        f"{label} & {report['shown']}/{report['views']} & "
        f"{report['correct_iou25']} & {report['correct_iou50']} & "
        f"{percentage(report['precision_iou25'])} ({bounds}) "
        + "\\" * 2
    )


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1] / "research"
    reports = root / "experiments"
    baseline = json.loads((reports / "vision_results.json").read_text())["test"]
    full = json.loads((reports / "neural_results.json").read_text())["test"]
    tiled = json.loads((reports / "tile_results.json").read_text())["test"]
    lines = [
        row("Logistic baseline", baseline["logistic"]),
        row("Random forest", baseline["forest"]),
        row("Whole-view CNN", full),
        row("Tiled CNN", tiled),
    ]
    target = root / "paper" / "tables" / "localization.tex"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(r"""% Generated by ml/paper_tables.py.
\begin{table}[htbp]
  \centering
  \caption{Test localization at validation-selected operating points. The final column reports selective precision in percent with a garment-bootstrap 95\% interval. Counts at each IoU threshold use only shown candidates.}
  \begin{tabular}{lrrrr}
    \toprule
    Detector & Shown & IoU $\geq$ 0.25 & IoU $\geq$ 0.50 & Precision (95\% CI) \\
    \midrule
""" + "\n".join(lines) + r"""
    \bottomrule
  \end{tabular}
  \label{tab:results}
\end{table}
""", encoding="utf-8")
